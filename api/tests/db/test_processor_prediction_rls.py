import pytest

from shared.db import login, use_client, use_service_client
from shared.models import LabelDataEnum, LabelSourceEnum, LabelTypeEnum
from shared.settings import settings


GEOMETRY = {
	'type': 'Polygon',
	'coordinates': [
		[
			[7.0, 47.0],
			[7.0, 47.01],
			[7.01, 47.01],
			[7.01, 47.0],
			[7.0, 47.0],
		]
	],
}


def _label_payload(dataset_id: int, user_id: str, label_data: LabelDataEnum) -> dict:
	return {
		'dataset_id': dataset_id,
		'user_id': user_id,
		'label_source': LabelSourceEnum.model_prediction,
		'label_type': LabelTypeEnum.semantic_segmentation,
		'label_data': label_data,
		'label_quality': 1,
	}


def test_processor_can_manage_cross_owner_prediction_records(
	datasets_with_mixed_access,
	test_user,
):
	dataset_id = datasets_with_mixed_access['private_id']
	processor_token = login(settings.PROCESSOR_USERNAME, settings.PROCESSOR_PASSWORD, use_cached_session=False)
	label_ids = []
	aoi_id = None

	try:
		with use_client(processor_token) as client:
			deadwood_label = (
				client.table(settings.labels_table)
				.insert(_label_payload(dataset_id, test_user, LabelDataEnum.deadwood))
				.execute()
			).data[0]
			forest_cover_label = (
				client.table(settings.labels_table)
				.insert(_label_payload(dataset_id, test_user, LabelDataEnum.forest_cover))
				.execute()
			).data[0]
			label_ids = [deadwood_label['id'], forest_cover_label['id']]

			client.table(settings.deadwood_geometries_table).insert(
				{'label_id': deadwood_label['id'], 'geometry': GEOMETRY}
			).execute()
			client.table(settings.forest_cover_geometries_table).insert(
				{'label_id': forest_cover_label['id'], 'geometry': GEOMETRY}
			).execute()
			client.table(settings.labels_table).update({'is_active': False}).eq(
				'id', deadwood_label['id']
			).execute()

			legacy_prediction_aoi = {
				'dataset_id': dataset_id,
				'user_id': test_user,
				'geometry': {'type': 'MultiPolygon', 'coordinates': [[GEOMETRY['coordinates']]]},
				'is_whole_image': False,
				'notes': 'Auto-generated by aoi_segmentation_v1',
			}
			aoi = client.table(settings.aois_table).insert(legacy_prediction_aoi).execute().data[0]
			aoi_id = aoi['id']
			assert aoi['source'] == 'ml_prediction'

			client.table(settings.aois_table).delete().eq('id', aoi_id).execute()
			assert client.table(settings.aois_table).select('id').eq('id', aoi_id).execute().data == []
	finally:
		with use_service_client() as client:
			if aoi_id is not None:
				client.table(settings.aois_table).delete().eq('id', aoi_id).execute()
			if label_ids:
				client.table(settings.labels_table).delete().in_('id', label_ids).execute()


def test_non_owner_cannot_create_prediction_records_for_another_users_dataset(
	datasets_with_mixed_access,
	test_user2,
):
	non_owner_token = login(settings.TEST_USER_EMAIL2, settings.TEST_USER_PASSWORD2, use_cached_session=False)
	payload = _label_payload(
		datasets_with_mixed_access['private_id'],
		test_user2,
		LabelDataEnum.deadwood,
	)

	with use_client(non_owner_token) as client:
		with pytest.raises(Exception, match='row-level security policy'):
			client.table(settings.labels_table).insert(payload).execute()


def test_processor_cannot_create_cross_owner_manual_labels(
	datasets_with_mixed_access,
	test_user,
):
	processor_token = login(settings.PROCESSOR_USERNAME, settings.PROCESSOR_PASSWORD, use_cached_session=False)
	payload = _label_payload(
		datasets_with_mixed_access['private_id'],
		test_user,
		LabelDataEnum.deadwood,
	)
	payload['label_source'] = LabelSourceEnum.visual_interpretation

	with use_client(processor_token) as client:
		with pytest.raises(Exception, match='row-level security policy'):
			client.table(settings.labels_table).insert(payload).execute()
