-- Acquisition-date decisions: the outcome of the date check, versioned.
--
-- The model's estimate (v2_acquisition_date_estimates) and its audit
-- suggestions only propose. A *decision* is what was concluded: whether the
-- reported date is valid, and whether the suggested date was accepted. It is
-- made by an auditor (saving the audit form) or, when enabled, automatically
-- by the processor. Exactly one decision per dataset is active; older ones are
-- never overwritten but deactivated with a date and a reason:
--   new_decision          a newer decision replaced it (re-audit)
--   estimate_contradicts  a new estimate (rerun, new model version) disagrees
--   date_edited           the dataset's date was edited by hand
--   cutoff                an operator deactivated all decisions before a date
-- A deactivated decision sends the date step back to review: the audit's date
-- fields are cleared, so the form is prefilled from the current suggestions.
--
-- Accepting the suggested date writes it to v2_datasets (full day) and marks
-- the date as aquisition_date_source = 'model_suggestion' with a pointer to the
-- decision, whose evidence snapshot (distribution, ranges, offset, surprise)
-- explains the change; the reported date is kept on the decision.

alter table public.dataset_audit
  add column if not exists accept_suggested_acquisition_date boolean;

create table if not exists public.acquisition_date_decisions (
  id bigint generated by default as identity primary key,
  dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
  source text not null check (source in ('auditor', 'automatic', 'legacy_audit')),
  decided_by uuid references auth.users (id) on delete set null,
  decided_at timestamptz not null default now(),
  -- is the reported date plausible?
  date_valid boolean not null,
  -- the suggested date: accepted, rejected, or null when there was none / undecided
  suggestion_decision text check (suggestion_decision in ('accepted', 'rejected')),
  suggested_date date,
  -- the dataset's date before (as reported) and after this decision
  reported_year smallint,
  reported_month smallint,
  reported_day smallint,
  resulting_year smallint,
  resulting_month smallint,
  resulting_day smallint,
  estimate_model_version text,
  estimate_model_type text,
  -- snapshot of the estimate the decision was based on (probabilities, ranges,
  -- offset, surprise, modes), so the evidence survives later reruns
  evidence jsonb not null default '{}'::jsonb,
  superseded_at timestamptz,
  superseded_reason text check (superseded_reason in ('new_decision', 'estimate_contradicts', 'date_edited', 'cutoff')),
  check ((superseded_at is null) = (superseded_reason is null)),
  check (suggestion_decision is distinct from 'accepted' or suggested_date is not null)
);

create unique index if not exists acquisition_date_decisions_one_active_idx
  on public.acquisition_date_decisions (dataset_id) where superseded_at is null;
create index if not exists acquisition_date_decisions_dataset_idx
  on public.acquisition_date_decisions (dataset_id, decided_at desc);

alter table public.v2_datasets
  add column if not exists aquisition_date_source text not null default 'reported'
    check (aquisition_date_source in ('reported', 'model_suggestion')),
  add column if not exists aquisition_date_decision_id bigint
    references public.acquisition_date_decisions (id) on delete set null;

