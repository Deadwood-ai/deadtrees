create table public.audit_checks (
	key text primary key check (key ~ '^[a-z][a-z0-9_]*$'),
	title text not null,
	description text not null default '',
	created_at timestamptz not null default now()
);

insert into public.audit_checks (key, title, description) values
	('dataset_evaluation', 'Dataset evaluation', 'Exclude, COG, thumbnail and reprocess flags and image properties, judged on the overview and native crops'),
	('georef', 'Georeferencing', 'Offset of the orthophoto against satellite references'),
	('acquisition_date', 'Acquisition date', 'Recorded flight date against the date model'),
	('prediction_quality', 'Prediction quality', 'Deadwood and forest cover predictions judged on crops');

-- mode decides what happens with a version's results:
--   review_all        every result goes to a person
--   review_uncertain  only unsure or disagreeing results go to a person
--   auto_apply        results apply without review
-- The worker registers versions (always review_all, inactive); operators switch
-- mode and the active version without a deploy.
create table public.audit_check_versions (
	id bigint generated by default as identity primary key,
	check_key text not null references public.audit_checks (key),
	version text not null check (version ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	mode public.audit_check_mode not null default 'review_all',
	is_active boolean not null default false,
	-- models, prompt versions, crop settings, thresholds, rule version
	config jsonb not null default '{}'::jsonb check (jsonb_typeof(config) = 'object'),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	updated_by uuid references auth.users (id) on delete set null,
	unique (check_key, version),
	unique (id, check_key)
);
create unique index audit_check_versions_one_active_idx on public.audit_check_versions (check_key) where is_active;

create function internal.stamp_audit_check_version()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if (new.check_key, new.version, new.config, new.created_at)
		is distinct from (old.check_key, old.version, old.config, old.created_at) then
		raise exception 'Only mode and is_active of a check version change; register a new version instead'
			using errcode = '55000';
	end if;
	new.updated_at := now();
	new.updated_by := auth.uid();
	return new;
end;
$$;
create trigger stamp_audit_check_version
before update on public.audit_check_versions
for each row execute function internal.stamp_audit_check_version();

-- One row per dataset, check version and run; every run is kept. A worker that
-- cannot reach a model (expired login) leaves its runs queued instead of failing them.
create table public.audit_check_runs (
	id bigint generated by default as identity primary key,
	check_key text not null,
	check_version_id bigint not null,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	queue text not null check (queue in ('upload', 'backfill', 'manual')),
	status public.audit_run_status not null default 'queued',
	-- what the run judged: ortho sha256, prediction label ids, crop settings
	inputs jsonb not null default '{}'::jsonb check (jsonb_typeof(inputs) = 'object'),
	-- check-specific evidence not tied to one assessor (reference matches, date
	-- curve, band statistics, duplicate hashes)
	evidence jsonb not null default '{}'::jsonb check (jsonb_typeof(evidence) = 'object'),
	-- crops done out of total, full or sampled, why sampling stopped
	coverage jsonb not null default '{}'::jsonb check (jsonb_typeof(coverage) = 'object'),
	-- tokens, calls and estimated cost per model
	cost jsonb not null default '{}'::jsonb check (jsonb_typeof(cost) = 'object'),
	error text,
	attempts smallint not null default 0 check (attempts >= 0),
	created_at timestamptz not null default now(),
	started_at timestamptz,
	finished_at timestamptz,
	foreign key (check_version_id, check_key) references public.audit_check_versions (id, check_key),
	unique (id, check_key, dataset_id),
	check ((finished_at is not null) = (status in ('done', 'failed'))),
	check (status <> 'failed' or error is not null)
);
create index audit_check_runs_dataset_idx on public.audit_check_runs (dataset_id, check_key);
create index audit_check_runs_open_idx on public.audit_check_runs (queue, created_at) where status in ('queued', 'running');
create index audit_check_runs_version_idx on public.audit_check_runs (check_version_id);

-- The run whose results count for a dataset and check.
create table public.audit_current_runs (
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	check_key text not null references public.audit_checks (key),
	run_id bigint not null,
	updated_at timestamptz not null default now(),
	primary key (dataset_id, check_key),
	foreign key (run_id, check_key, dataset_id) references public.audit_check_runs (id, check_key, dataset_id)
		on delete cascade
);
create index audit_current_runs_run_idx on public.audit_current_runs (run_id);

-- ---------------------------------------------------------------------------
-- Evidence: crops and stored images
-- ---------------------------------------------------------------------------

-- A crop is a window of one ortho version (v2_orthos keeps one row per dataset,
-- so its sha256 identifies the version). The window is given on the 10 cm grid
-- the CLIP tiles use (v2_tile_embeddings pixel_x0..y1), not by tile id, so it
-- survives an embedding rerun. A new ortho makes new crops; a prediction rerun
-- re-judges the same crops. One window can belong to several crop sets:
--   exclude     the tiles with the most predicted cover, for the exclude decision
--   training    stratified tiles, mapped to Sentinel-2 pixels by area overlap
--   evaluation  native crops of the dataset evaluation
-- A picker that selects an existing window appends its set; nothing else changes.
create table public.audit_crops (
	id bigint generated by default as identity primary key,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	ortho_sha256 text not null check (ortho_sha256 ~ '^[0-9a-f]{64}$'),
	crop_sets text[] not null check (cardinality(crop_sets) > 0 and crop_sets <@ array['exclude', 'training', 'evaluation']),
	pixel_x0 integer not null,
	pixel_y0 integer not null,
	pixel_x1 integer not null,
	pixel_y1 integer not null,
	geometry geometry(Polygon, 4326) not null,
	-- the stored image: 5 cm, or native when coarser
	mpp real not null check (mpp > 0),
	size_px integer not null check (size_px > 0),
	-- per set: picker and version, predicted cover at selection time, stratum,
	-- Sentinel-2 overlap, e.g. {"training": {"picker": "s2-stratified-v1", "stratum": 3}}
	selection jsonb not null default '{}'::jsonb check (jsonb_typeof(selection) = 'object'),
	created_at timestamptz not null default now(),
	unique (dataset_id, ortho_sha256, pixel_x0, pixel_y0, pixel_x1, pixel_y1),
	unique (id, dataset_id),
	check (pixel_x0 >= 0 and pixel_y0 >= 0 and pixel_x1 > pixel_x0 and pixel_y1 > pixel_y0)
);

create function internal.append_only_audit_crop_sets()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if not (new.crop_sets @> old.crop_sets and new.selection @> old.selection) then
		raise exception 'Crop sets and selection only grow' using errcode = '55000';
	end if;
	return new;
end;
$$;
create trigger append_only_audit_crop_sets
before update on public.audit_crops
for each row execute function internal.append_only_audit_crop_sets();
create index audit_crops_geometry_idx on public.audit_crops using gist (geometry);

-- Every image a check judged, stored on the storage server and shown to
-- reviewers: the raw crop once per ortho, overlays once per prediction label,
-- the dataset overview and thumbnail once per ortho.
create table public.audit_images (
	id bigint generated by default as identity primary key,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	ortho_sha256 text not null check (ortho_sha256 ~ '^[0-9a-f]{64}$'),
	crop_id bigint,
	label_id bigint,               -- the prediction an overlay shows
	kind text not null check (kind in ('raw', 'deadwood_overlay', 'forest_cover_overlay', 'overview', 'thumbnail')),
	-- relative to the storage server's data directory
	storage_path text not null check (storage_path ~ '^[A-Za-z0-9_-][A-Za-z0-9_./-]*$' and storage_path !~ '(^|/)\.\.(/|$)'),
	content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
	width integer not null check (width > 0),
	height integer not null check (height > 0),
	mpp real check (mpp > 0),
	bytes integer check (bytes > 0),
	sha256 text check (sha256 ~ '^[0-9a-f]{64}$'),
	created_at timestamptz not null default now(),
	foreign key (crop_id, dataset_id) references public.audit_crops (id, dataset_id) on delete cascade,
	unique nulls not distinct (dataset_id, ortho_sha256, crop_id, label_id, kind),
	check ((kind in ('overview', 'thumbnail')) = (crop_id is null)),
	check ((kind in ('deadwood_overlay', 'forest_cover_overlay')) = (label_id is not null))
);
create index audit_images_crop_idx on public.audit_images (crop_id);

-- ---------------------------------------------------------------------------
-- Assessments
-- ---------------------------------------------------------------------------

-- One row per assessor, target and layer; append-only. The target is a crop, or
-- the dataset when crop_id is null. Layers: image (the m0 gate on a crop, the
-- dataset evaluation on a dataset), deadwood, forest_cover, georef,
-- acquisition_date, phenology. The m0 gate is layer image on a crop: ok =
-- assessable, major = not assessable, modes {"m0_not_assessable": {...}}.
-- Every mode key names an error, so a high likelihood always means a problem.
create table public.audit_assessments (
	id bigint generated by default as identity primary key,
	check_key text not null references public.audit_checks (key),
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	crop_id bigint,
	-- required for models and rules; for people, the run whose results they judged
	run_id bigint,
	layer text not null check (layer in ('image', 'deadwood', 'forest_cover', 'georef', 'acquisition_date', 'phenology')),
	-- the prediction judged (null for image checks). No foreign key: a prediction
	-- rerun replaces the label and makes the row stale, and the row stays as history.
	label_id bigint,
	assessor_kind public.audit_assessor_kind not null,
	assessor_user_id uuid references auth.users (id),
	-- model or rule name and its prompt or rule version: 'luna-medium' / 'v4', 'band_check' / 'v1'
	model text check (model ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	prompt_version text check (prompt_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	assessor text generated always as (coalesce(assessor_user_id::text, model || '/' || prompt_version)) stored,
	verdict public.audit_verdict not null,
	major_likelihood real check (major_likelihood between 0 and 100),
	-- failure modes and flags by key, named by the check (prediction quality
	-- m1..m7, dataset evaluation cog_issue, blurry, ...). People: {"m1_dead_missed": true}.
	-- Models and rules: {"m1_dead_missed": {"likelihood": 80, "area_pct": 12}}.
	modes jsonb not null default '{}'::jsonb check (jsonb_typeof(modes) = 'object'),
	-- why a person marks a check wrong: a fixed choice of the check plus free text
	reason_code text check (reason_code ~ '^[a-z][a-z0-9_]*$'),
	reason_text text check (length(reason_text) <= 2000),
	-- check-specific parsed answer (exclude reason, COG issue, suggested date, p90)
	details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
	raw jsonb,                     -- the model's reply as returned
	created_at timestamptz not null default now(),
	foreign key (crop_id, dataset_id) references public.audit_crops (id, dataset_id) on delete cascade,
	foreign key (run_id, check_key, dataset_id) references public.audit_check_runs (id, check_key, dataset_id)
		on delete cascade,
	check (
		case assessor_kind
			when 'person' then assessor_user_id is not null and model is null and prompt_version is null and raw is null
			else assessor_user_id is null and model is not null and prompt_version is not null and run_id is not null
		end
	)
);
create index audit_assessments_target_idx on public.audit_assessments (dataset_id, check_key, crop_id, layer);
create index audit_assessments_crop_idx on public.audit_assessments (crop_id) where crop_id is not null;
create index audit_assessments_run_idx on public.audit_assessments (run_id) where run_id is not null;
create index audit_assessments_person_idx on public.audit_assessments (assessor_user_id) where assessor_user_id is not null;

