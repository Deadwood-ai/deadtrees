-- ---------------------------------------------------------------------------
-- Assessments
-- ---------------------------------------------------------------------------

-- One row per assessor, target and layer; append-only. The target is a crop, or
-- the dataset when crop_id is null. Layers: image (the m0 gate on a crop, the
-- dataset evaluation on a dataset), deadwood, forest_cover, georef,
-- acquisition_date, phenology. The m0 gate is layer image on a crop: ok =
-- assessable, major = not assessable, modes {"m0_not_assessable": {...}}.
-- Every mode key names an error, so a high likelihood always means a problem.
create table audit.assessments (
	id bigint generated by default as identity primary key,
	check_key text not null references audit.checks (key),
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	crop_id bigint,
	-- required for models and rules; for people, the run whose results they judged
	run_id bigint,
	layer text not null check (layer in ('image', 'deadwood', 'forest_cover', 'georef', 'acquisition_date', 'phenology')),
	-- the prediction judged (null for image checks). No foreign key: a prediction
	-- rerun replaces the label and makes the row stale, and the row stays as history.
	label_id bigint,
	assessor_kind audit.assessor_kind not null,
	assessor_user_id uuid references auth.users (id),
	-- model or rule name and its prompt or rule version: 'luna-medium' / 'v4', 'band_check' / 'v1'
	model text check (model ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	prompt_version text check (prompt_version ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	assessor text generated always as (coalesce(assessor_user_id::text, model || '/' || prompt_version)) stored,
	verdict audit.verdict not null,
	major_likelihood real check (major_likelihood between 0 and 100),
	-- failure modes and flags by key, named by the check (prediction quality
	-- m1..m7, dataset evaluation cog_issue, blurry, ...). People: {"m1_dead_missed": true}.
	-- Models and rules: {"m1_dead_missed": {"likelihood": 80, "area_pct": 12}}.
	modes jsonb not null default '{}'::jsonb check (jsonb_typeof(modes) = 'object'),
	-- why a person marks a check wrong: a fixed choice of the check plus free text
	reason_code text check (reason_code ~ '^[a-z][a-z0-9_]*$'),
	reason_text text check (length(reason_text) <= 2000),
	-- check-specific parsed answer (exclude reason, COG issue, suggested date, p90)
	details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
	raw jsonb,                     -- the model's reply as returned
	-- set on person rows imported from an older record that is not benchmark
	-- truth, e.g. 'dataset_audit' for the audits before the redo (DT-1487); null
	-- for every judgement made in this system. Only the service role sets it.
	imported_from text check (imported_from ~ '^[a-z][a-z0-9_]*$'),
	created_at timestamptz not null default now(),
	foreign key (crop_id, dataset_id) references audit.crops (id, dataset_id) on delete cascade,
	foreign key (run_id, check_key, dataset_id) references audit.runs (id, check_key, dataset_id)
		on delete cascade,
	check (imported_from is null or assessor_kind = 'person'),
	check (
		case assessor_kind
			when 'person' then assessor_user_id is not null and model is null and prompt_version is null and raw is null
			else assessor_user_id is null and model is not null and prompt_version is not null and run_id is not null
		end
	)
);
create index assessments_target_idx on audit.assessments (dataset_id, check_key, crop_id, layer);
create index assessments_crop_idx on audit.assessments (crop_id) where crop_id is not null;
create index assessments_run_idx on audit.assessments (run_id) where run_id is not null;
create index assessments_person_idx on audit.assessments (assessor_user_id) where assessor_user_id is not null;
create index assessments_imported_idx on audit.assessments (dataset_id) where imported_from is not null;

