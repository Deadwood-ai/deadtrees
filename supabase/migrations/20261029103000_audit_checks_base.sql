-- ---------------------------------------------------------------------------
-- Evidence: crops and stored images
-- ---------------------------------------------------------------------------

-- A crop is an area of one ortho version (v2_orthos keeps one row per dataset,
-- so its sha256 identifies the version). Crops the checks pick are windows on
-- the 10 cm grid the CLIP tiles use (v2_tile_embeddings pixel_x0..y1), not tile
-- ids, so they survive an embedding rerun. Crops made elsewhere (the DT-1272
-- gold crops, centred on predictions or random points, of varying size) have no
-- window and are identified by their footprint. A new ortho makes new crops; a
-- prediction rerun re-judges the same crops. One crop can belong to several sets:
--   exclude     the tiles with the most predicted cover, for the exclude decision
--   training    stratified tiles, mapped to Sentinel-2 pixels by area overlap
--   evaluation  native crops of the dataset evaluation
--   benchmark   crops picked for a benchmark (audit.benchmark_members)
-- A picker that selects an existing crop appends its set; nothing else changes.
create table audit.crops (
	id bigint generated by default as identity primary key,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	ortho_sha256 text not null check (ortho_sha256 ~ '^[0-9a-f]{64}$'),
	crop_sets text[] not null
		check (cardinality(crop_sets) > 0 and crop_sets <@ array['exclude', 'training', 'evaluation', 'benchmark']),
	-- the window on the 10 cm CLIP grid; null for crops made off the grid
	pixel_x0 integer,
	pixel_y0 integer,
	pixel_x1 integer,
	pixel_y1 integer,
	geometry geometry(Polygon, 4326) not null,
	-- the stored image: usually 5 cm and 1024 px, or native when coarser
	mpp real not null check (mpp > 0),
	size_px integer not null check (size_px > 0),
	-- per set: picker and version, predicted cover at selection time, stratum,
	-- Sentinel-2 overlap, e.g. {"training": {"picker": "s2-stratified-v1", "stratum": 3}}
	selection jsonb not null default '{}'::jsonb check (jsonb_typeof(selection) = 'object'),
	created_at timestamptz not null default now(),
	unique (dataset_id, ortho_sha256, pixel_x0, pixel_y0, pixel_x1, pixel_y1),
	unique (id, dataset_id),
	check (
		num_nulls(pixel_x0, pixel_y0, pixel_x1, pixel_y1) in (0, 4)
		and (pixel_x0 is null or (pixel_x0 >= 0 and pixel_y0 >= 0 and pixel_x1 > pixel_x0 and pixel_y1 > pixel_y0))
	)
);
create unique index crops_off_grid_idx on audit.crops (dataset_id, ortho_sha256, md5(geometry::text))
	where pixel_x0 is null;

create function internal.append_only_audit_crop_sets()
