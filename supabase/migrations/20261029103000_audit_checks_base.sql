-- Model and rule rows that count now: those of each dataset's current run, plus
-- the model rows of the run a rule-only run recomputed from (its old rule rows
-- stay history).
create view audit.current_assessments
with (security_invoker = true)
as
select a.*
from audit.current_runs c
join audit.runs r on r.id = c.run_id
join audit.assessments a on a.dataset_id = c.dataset_id and a.check_key = c.check_key
	and (a.run_id = c.run_id or (a.run_id = r.source_run_id and a.assessor_kind = 'model'));

-- Latest row per target, layer and assessor: a correction replaces the earlier
-- answer of the same assessor, while every answer stays in the table. A native
-- answer replaces the same person's imported one whatever its date. Benchmarks
-- and agreement metrics filter on imported_from is null.
create view audit.latest_assessments
with (security_invoker = true)
as
select distinct on (check_key, dataset_id, crop_id, layer, assessor) *
from audit.assessments
order by check_key, dataset_id, crop_id, layer, assessor, imported_from is not null, created_at desc, id desc;

-- Targets for the adjudication list: people disagree with each other, or a
-- person disagrees with a model or rule answer in the dataset's current run.
-- Imported answers never count as people disagreeing; where one differs from the
-- current models, legacy_and_models_disagree puts the dataset up for an early look.
-- Compares verdicts only, so it holds for every check's own modes.
create view audit.disagreements
with (security_invoker = true)
as
with counted as (
	-- filter to the current run first, so a newer run that is not current yet
	-- cannot hide the current run's answers
	select distinct on (a.check_key, a.dataset_id, a.crop_id, a.layer, a.assessor) a.*
	from (
		select * from audit.assessments where assessor_kind = 'person'
		union all
		select * from audit.current_assessments
	) a
	order by a.check_key, a.dataset_id, a.crop_id, a.layer, a.assessor, a.imported_from is not null, a.created_at desc, a.id desc
), targets as (
	select
		check_key, dataset_id, crop_id, layer,
		jsonb_object_agg(assessor, verdict order by assessor) as verdicts,
		array_agg(distinct verdict) filter (where assessor_kind = 'person' and imported_from is null) as people,
		array_agg(distinct verdict) filter (where imported_from is not null) as legacy,
		array_agg(distinct verdict) filter (where assessor_kind <> 'person') as models,
		max(created_at) as last_assessed_at
	from counted
	group by check_key, dataset_id, crop_id, layer
)
select
	check_key, dataset_id, crop_id, layer, verdicts,
	coalesce(cardinality(people) > 1, false) as people_disagree,
	people is not null and models is not null and people is distinct from models as people_and_models_disagree,
	legacy is not null and models is not null and legacy is distinct from models as legacy_and_models_disagree,
	last_assessed_at
from targets
where cardinality(people) > 1
	or (models is not null and (people is distinct from models and people is not null
		or legacy is distinct from models and legacy is not null));

-- What needs a person: one row per dataset, check and layer with a dataset-level
-- verdict in the current run. The verdict comes from the run's dataset-level rule
-- rows (a check's dataset rule, e.g. "deadwood bad when 2 of 10 crops are major"),
-- else its dataset-level model rows (georef, date). The worst verdict counts. The
-- version's mode decides:
--   review_all        always, reason review_all
--   review_uncertain  when a verdict is unsure or the assessors disagree
--   auto_apply        only the spot-check sample (config spot_check_pct, default 5)
-- A native person answer on the dataset for the judged prediction marks it reviewed.
create view audit.review_queue
with (security_invoker = true)
as
with dataset_rows as (
	select a.*, bool_or(a.assessor_kind = 'rule') over (partition by a.dataset_id, a.check_key, a.layer) as has_rule
	from audit.current_assessments a
	where a.crop_id is null
), verdicts as (
	select
		d.dataset_id, d.check_key, d.layer, c.run_id,
		jsonb_object_agg(d.assessor, d.verdict order by d.assessor) as verdicts,
		array_agg(distinct d.verdict) as distinct_verdicts,
		array_remove(array_agg(distinct d.label_id), null) as label_ids
	from dataset_rows d
	join audit.current_runs c on c.dataset_id = d.dataset_id and c.check_key = d.check_key
	where d.assessor_kind = 'rule' or not d.has_rule
	group by d.dataset_id, d.check_key, d.layer, c.run_id
), judged as (
	select
		v.*, r.check_version_id, cv.version, cv.mode,
		case
			when 'major' = any(v.distinct_verdicts) then 'major'
			when 'unsure' = any(v.distinct_verdicts) then 'unsure'
			when 'minor' = any(v.distinct_verdicts) then 'minor'
			else 'ok'
		end::audit.verdict as verdict,
		case
			when cv.mode = 'review_all' then 'review_all'
			when 'unsure' = any(v.distinct_verdicts) then 'unsure'
			when cardinality(v.distinct_verdicts) > 1 then 'models_disagree'
			when cv.mode = 'auto_apply'
				and ('x' || substr(md5('audit-spot-v1:' || v.dataset_id || ':' || r.check_version_id), 1, 8))::bit(32)::bigint % 100
					< coalesce((cv.config ->> 'spot_check_pct')::integer, 5) then 'spot_check'
		end as reason,
		exists (
			select 1 from audit.assessments p
			where p.assessor_kind = 'person' and p.imported_from is null and p.crop_id is null
				and p.dataset_id = v.dataset_id and p.check_key = v.check_key and p.layer = v.layer
				and (p.label_id is null or p.label_id = any(v.label_ids))
		) as reviewed
	from verdicts v
	join audit.runs r on r.id = v.run_id
	join audit.check_versions cv on cv.id = r.check_version_id
)
select
	dataset_id, check_key, layer, run_id, check_version_id, version, mode, verdict, verdicts,
	reason is not null and not reviewed as needs_review,
	reason, reviewed
from judged;

-- Activate a check version, optionally with the mode of the version it replaces,
-- so a benchmark-approved change does not send everything back to review.
create function audit.activate_version(p_version_id bigint, p_inherit_mode boolean default false)
returns audit.check_versions
language plpgsql set search_path = ''
as $$
declare
	v_target audit.check_versions;
	v_previous audit.check_versions;
begin
	if not public.can_operate() and current_setting('role', true) is distinct from 'service_role'
		and (select auth.jwt() ->> 'role') is distinct from 'service_role' then
		raise exception 'Only operators activate check versions' using errcode = '42501';
	end if;
	select * into v_target from audit.check_versions where id = p_version_id for update;
	if not found then
		raise exception 'Check version % does not exist', p_version_id using errcode = 'P0002';
	end if;
	select * into v_previous from audit.check_versions
	where check_key = v_target.check_key and is_active and id <> p_version_id for update;
	if found then
		update audit.check_versions set is_active = false where id = v_previous.id;
	end if;
	update audit.check_versions
	set is_active = true,
		mode = case when p_inherit_mode and v_previous.id is not null then v_previous.mode else mode end
	where id = p_version_id
	returning * into v_target;
	return v_target;
end;
$$;
revoke all on function audit.activate_version(bigint, boolean) from public, anon;
grant execute on function audit.activate_version(bigint, boolean) to authenticated, service_role;

