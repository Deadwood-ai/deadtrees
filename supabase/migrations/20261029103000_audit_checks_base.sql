-- Latest row per target, layer and assessor: a correction replaces the earlier
-- answer of the same assessor, while every answer stays in the table. A native
-- answer replaces the same person's imported one whatever its date. Benchmarks
-- and agreement metrics filter on imported_from is null.
create view public.audit_latest_assessments
with (security_invoker = true)
as
select distinct on (check_key, dataset_id, crop_id, layer, assessor) *
from public.audit_assessments
order by check_key, dataset_id, crop_id, layer, assessor, imported_from is not null, created_at desc, id desc;

-- Targets for the adjudication list: people disagree with each other, or a
-- person disagrees with a model or rule answer in the dataset's current run.
-- Imported answers never count as people disagreeing; where one differs from the
-- current models, legacy_and_models_disagree puts the dataset up for an early look.
-- Compares verdicts only, so it holds for every check's own modes.
create view public.audit_disagreements
with (security_invoker = true)
as
with counted as (
	-- filter to the current run first, so a newer run that is not current yet
	-- cannot hide the current run's answers
	select distinct on (a.check_key, a.dataset_id, a.crop_id, a.layer, a.assessor) a.*
	from public.audit_assessments a
	left join public.audit_current_runs c on c.dataset_id = a.dataset_id and c.check_key = a.check_key
	where a.assessor_kind = 'person' or a.run_id = c.run_id
	order by a.check_key, a.dataset_id, a.crop_id, a.layer, a.assessor, a.imported_from is not null, a.created_at desc, a.id desc
), targets as (
	select
		check_key, dataset_id, crop_id, layer,
		jsonb_object_agg(assessor, verdict order by assessor) as verdicts,
		array_agg(distinct verdict) filter (where assessor_kind = 'person' and imported_from is null) as people,
		array_agg(distinct verdict) filter (where imported_from is not null) as legacy,
		array_agg(distinct verdict) filter (where assessor_kind <> 'person') as models,
		max(created_at) as last_assessed_at
	from counted
	group by check_key, dataset_id, crop_id, layer
)
select
	check_key, dataset_id, crop_id, layer, verdicts,
	coalesce(cardinality(people) > 1, false) as people_disagree,
	people is not null and models is not null and people is distinct from models as people_and_models_disagree,
	legacy is not null and models is not null and legacy is distinct from models as legacy_and_models_disagree,
	last_assessed_at
from targets
where cardinality(people) > 1
	or (models is not null and (people is distinct from models and people is not null
		or legacy is distinct from models and legacy is not null));

-- ---------------------------------------------------------------------------
-- Benchmarks
-- ---------------------------------------------------------------------------

-- Every dataset has a fixed side, development or holdout, by a hash of its id
-- (1 in 5 held out). It is the default split for new benchmark members. Never
-- change the rule: that would move datasets between the sides.
create function public.audit_benchmark_split(p_dataset_id bigint)
returns text
language sql immutable set search_path = ''
as $$
	select case when ('x' || substr(md5('audit-split-v1:' || p_dataset_id), 1, 8))::bit(32)::bigint % 5 = 0
		then 'holdout' else 'dev' end;
$$;
revoke all on function public.audit_benchmark_split(bigint) from public, anon;
grant execute on function public.audit_benchmark_split(bigint) to authenticated, service_role, analyst;

-- A benchmark is a fixed set of crops or datasets for one check. Truth is the
-- native person rows in audit_assessments (imported_from is null); a benchmark
-- only fixes its members and records scores. Freezing makes the members final,
-- and a bigger set is a new version.
create table public.audit_benchmarks (
	id bigint generated by default as identity primary key,
	check_key text not null references public.audit_checks (key),
	name text not null check (name ~ '^[a-z0-9][a-z0-9_-]*$'),     -- e.g. 'pq-gold-dt1272'
	version text not null check (version ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	description text not null default '',
	frozen_at timestamptz,
	created_by uuid default auth.uid() references auth.users (id) on delete set null,
	created_at timestamptz not null default now(),
	unique (name, version),
	unique (id, check_key)
);

create function internal.guard_audit_benchmark()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if old.frozen_at is not null then
		raise exception 'Benchmark %/% is frozen; create a new version instead', old.name, old.version
			using errcode = '55000';
	end if;
	if tg_op = 'DELETE' then
		return old;
	end if;
	if (new.check_key, new.name, new.version, new.created_by, new.created_at)
		is distinct from (old.check_key, old.name, old.version, old.created_by, old.created_at) then
		raise exception 'Only the description and frozen_at of a benchmark change' using errcode = '55000';
	end if;
	return new;
end;
$$;
create trigger guard_audit_benchmark
before update or delete on public.audit_benchmarks
for each row execute function internal.guard_audit_benchmark();

-- The target is a crop, or the dataset when crop_id is null. All members from
-- one dataset share its split, so a dataset never sits on both sides.
create table public.audit_benchmark_members (
	id bigint generated by default as identity primary key,
	benchmark_id bigint not null references public.audit_benchmarks (id) on delete cascade,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	crop_id bigint,
	-- defaults to audit_benchmark_split(dataset_id); a set frozen earlier keeps its own
	split text not null check (split in ('dev', 'holdout')),
	added_at timestamptz not null default now(),
	foreign key (crop_id, dataset_id) references public.audit_crops (id, dataset_id) on delete cascade,
	unique nulls not distinct (benchmark_id, dataset_id, crop_id)
);
create index audit_benchmark_members_dataset_idx on public.audit_benchmark_members (dataset_id);

create function internal.guard_audit_benchmark_member()
returns trigger
language plpgsql set search_path = ''
as $$
declare
	v_benchmark bigint := case when tg_op = 'DELETE' then old.benchmark_id else new.benchmark_id end;
begin
	if tg_op = 'UPDATE' then
		raise exception 'Benchmark members do not change; remove and add instead' using errcode = '55000';
	end if;
	-- a deleted dataset or crop takes its members along, from frozen benchmarks too
	if tg_op = 'DELETE' and pg_trigger_depth() > 1 then
		return old;
	end if;
	if (select frozen_at from public.audit_benchmarks where id = v_benchmark) is not null then
		raise exception 'The benchmark is frozen; create a new version instead' using errcode = '55000';
	end if;
	if tg_op = 'DELETE' then
		return old;
	end if;
	new.split := coalesce(new.split, public.audit_benchmark_split(new.dataset_id));
	if exists (
		select 1 from public.audit_benchmark_members m
		where m.benchmark_id = new.benchmark_id and m.dataset_id = new.dataset_id and m.split <> new.split
	) then
		raise exception 'All members from dataset % share one split', new.dataset_id using errcode = '23514';
	end if;
	return new;
end;
$$;
create trigger guard_audit_benchmark_member
before insert or update or delete on public.audit_benchmark_members
for each row execute function internal.guard_audit_benchmark_member();

-- One row per scoring of a check version on a frozen benchmark; append-only.
create table public.audit_benchmark_scores (
	id bigint generated by default as identity primary key,
	benchmark_id bigint not null,
	check_key text not null,
	check_version_id bigint not null,
	split text not null check (split in ('dev', 'holdout', 'all')),
	-- n, auc, catch rate, false exclude rate, ...
	metrics jsonb not null check (jsonb_typeof(metrics) = 'object'),
	-- the benchmark runs the score was computed from
	run_ids bigint[] not null default '{}',
	scorer text not null check (scorer ~ '^[A-Za-z0-9][A-Za-z0-9._/-]*$'),  -- script and version
	notes text not null default '',
	scored_at timestamptz not null default now(),
	foreign key (benchmark_id, check_key) references public.audit_benchmarks (id, check_key) on delete cascade,
	foreign key (check_version_id, check_key) references public.audit_check_versions (id, check_key)
);
create index audit_benchmark_scores_benchmark_idx on public.audit_benchmark_scores (benchmark_id, check_version_id);

create function internal.require_frozen_audit_benchmark()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if (select frozen_at from public.audit_benchmarks where id = new.benchmark_id) is null then
		raise exception 'Freeze the benchmark before scoring on it' using errcode = '55000';
	end if;
	return new;
end;
$$;
create trigger require_frozen_audit_benchmark
before insert on public.audit_benchmark_scores
for each row execute function internal.require_frozen_audit_benchmark();
create trigger reject_audit_benchmark_score_update
before update on public.audit_benchmark_scores
for each row execute function internal.reject_audit_row_update();

