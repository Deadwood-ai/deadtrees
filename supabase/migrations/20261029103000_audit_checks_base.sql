create table public.audit_checks (
	key text primary key check (key ~ '^[a-z][a-z0-9_]*$'),
	title text not null,
	description text not null default '',
	created_at timestamptz not null default now()
);

insert into public.audit_checks (key, title, description) values
	('dataset_evaluation', 'Dataset evaluation', 'Exclude, COG, thumbnail and reprocess flags and image properties, judged on the overview and native crops'),
	('georef', 'Georeferencing', 'Offset of the orthophoto against satellite references'),
	('acquisition_date', 'Acquisition date', 'Recorded flight date against the date model'),
	('prediction_quality', 'Prediction quality', 'Deadwood and forest cover predictions judged on crops');

-- mode decides what happens with a version's results:
--   review_all        every result goes to a person
--   review_uncertain  only unsure or disagreeing results go to a person
--   auto_apply        results apply without review
-- The worker registers versions (always review_all, inactive); operators switch
-- mode and the active version without a deploy.
create table public.audit_check_versions (
	id bigint generated by default as identity primary key,
	check_key text not null references public.audit_checks (key),
	version text not null check (version ~ '^[A-Za-z0-9][A-Za-z0-9._-]*$'),
	mode public.audit_check_mode not null default 'review_all',
	is_active boolean not null default false,
	-- models, prompt versions, crop settings, thresholds, rule version
	config jsonb not null default '{}'::jsonb check (jsonb_typeof(config) = 'object'),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	updated_by uuid references auth.users (id) on delete set null,
	unique (check_key, version),
	unique (id, check_key)
);
create unique index audit_check_versions_one_active_idx on public.audit_check_versions (check_key) where is_active;

create function internal.stamp_audit_check_version()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if (new.check_key, new.version, new.config, new.created_at)
		is distinct from (old.check_key, old.version, old.config, old.created_at) then
		raise exception 'Only mode and is_active of a check version change; register a new version instead'
			using errcode = '55000';
	end if;
	new.updated_at := now();
	new.updated_by := auth.uid();
	return new;
end;
$$;
create trigger stamp_audit_check_version
before update on public.audit_check_versions
for each row execute function internal.stamp_audit_check_version();

-- One row per dataset, check version and run; every run is kept. A worker that
-- cannot reach a model (expired login) leaves its runs queued instead of failing them.
create table public.audit_check_runs (
	id bigint generated by default as identity primary key,
	check_key text not null,
	check_version_id bigint not null,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	-- benchmark runs score a candidate version on a benchmark's members: they stay
	-- out of the production queues and cost caps and never become the current run
	queue text not null check (queue in ('upload', 'backfill', 'manual', 'benchmark')),
	status public.audit_run_status not null default 'queued',
	-- what the run judged: ortho sha256, prediction label ids, crop settings
	inputs jsonb not null default '{}'::jsonb check (jsonb_typeof(inputs) = 'object'),
	-- check-specific evidence not tied to one assessor (reference matches, date
	-- curve, band statistics, duplicate hashes)
	evidence jsonb not null default '{}'::jsonb check (jsonb_typeof(evidence) = 'object'),
	-- crops done out of total, full or sampled, why sampling stopped
	coverage jsonb not null default '{}'::jsonb check (jsonb_typeof(coverage) = 'object'),
	-- tokens, calls and estimated cost per model
	cost jsonb not null default '{}'::jsonb check (jsonb_typeof(cost) = 'object'),
	error text,
	attempts smallint not null default 0 check (attempts >= 0),
	created_at timestamptz not null default now(),
	started_at timestamptz,
	finished_at timestamptz,
	foreign key (check_version_id, check_key) references public.audit_check_versions (id, check_key),
	unique (id, check_key, dataset_id),
	check ((finished_at is not null) = (status in ('done', 'failed'))),
	check (status <> 'failed' or error is not null)
);
create index audit_check_runs_dataset_idx on public.audit_check_runs (dataset_id, check_key);
create index audit_check_runs_open_idx on public.audit_check_runs (queue, created_at) where status in ('queued', 'running');
create index audit_check_runs_version_idx on public.audit_check_runs (check_version_id);

-- The run whose results count for a dataset and check.
create table public.audit_current_runs (
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	check_key text not null references public.audit_checks (key),
	run_id bigint not null,
	updated_at timestamptz not null default now(),
	primary key (dataset_id, check_key),
	foreign key (run_id, check_key, dataset_id) references public.audit_check_runs (id, check_key, dataset_id)
		on delete cascade
);
create index audit_current_runs_run_idx on public.audit_current_runs (run_id);

create function internal.reject_benchmark_current_run()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if exists (select 1 from public.audit_check_runs r where r.id = new.run_id and r.queue = 'benchmark') then
		raise exception 'A benchmark run never becomes the current run' using errcode = '23514';
	end if;
	return new;
end;
$$;
create trigger reject_benchmark_current_run
before insert or update on public.audit_current_runs
for each row execute function internal.reject_benchmark_current_run();

-- ---------------------------------------------------------------------------
-- Evidence: crops and stored images
-- ---------------------------------------------------------------------------

-- A crop is an area of one ortho version (v2_orthos keeps one row per dataset,
-- so its sha256 identifies the version). Crops the checks pick are windows on
-- the 10 cm grid the CLIP tiles use (v2_tile_embeddings pixel_x0..y1), not tile
-- ids, so they survive an embedding rerun. Crops made elsewhere (the DT-1272
-- gold crops, centred on predictions or random points, of varying size) have no
-- window and are identified by their footprint. A new ortho makes new crops; a
-- prediction rerun re-judges the same crops. One crop can belong to several sets:
--   exclude     the tiles with the most predicted cover, for the exclude decision
--   training    stratified tiles, mapped to Sentinel-2 pixels by area overlap
--   evaluation  native crops of the dataset evaluation
--   benchmark   crops picked for a benchmark (audit_benchmark_members)
-- A picker that selects an existing crop appends its set; nothing else changes.
create table public.audit_crops (
	id bigint generated by default as identity primary key,
	dataset_id bigint not null references public.v2_datasets (id) on delete cascade,
	ortho_sha256 text not null check (ortho_sha256 ~ '^[0-9a-f]{64}$'),
	crop_sets text[] not null
		check (cardinality(crop_sets) > 0 and crop_sets <@ array['exclude', 'training', 'evaluation', 'benchmark']),
	-- the window on the 10 cm CLIP grid; null for crops made off the grid
	pixel_x0 integer,
	pixel_y0 integer,
	pixel_x1 integer,
	pixel_y1 integer,
	geometry geometry(Polygon, 4326) not null,
	-- the stored image: usually 5 cm and 1024 px, or native when coarser
	mpp real not null check (mpp > 0),
	size_px integer not null check (size_px > 0),
	-- per set: picker and version, predicted cover at selection time, stratum,
	-- Sentinel-2 overlap, e.g. {"training": {"picker": "s2-stratified-v1", "stratum": 3}}
	selection jsonb not null default '{}'::jsonb check (jsonb_typeof(selection) = 'object'),
	created_at timestamptz not null default now(),
	unique (dataset_id, ortho_sha256, pixel_x0, pixel_y0, pixel_x1, pixel_y1),
	unique (id, dataset_id),
	check (
		num_nulls(pixel_x0, pixel_y0, pixel_x1, pixel_y1) in (0, 4)
		and (pixel_x0 is null or (pixel_x0 >= 0 and pixel_y0 >= 0 and pixel_x1 > pixel_x0 and pixel_y1 > pixel_y0))
	)
);
create unique index audit_crops_off_grid_idx on public.audit_crops (dataset_id, ortho_sha256, md5(geometry::text))
	where pixel_x0 is null;

create function internal.append_only_audit_crop_sets()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	if not (new.crop_sets @> old.crop_sets and new.selection @> old.selection) then
		raise exception 'Crop sets and selection only grow' using errcode = '55000';
	end if;
	return new;
end;
$$;
create trigger append_only_audit_crop_sets
before update on public.audit_crops
for each row execute function internal.append_only_audit_crop_sets();
create index audit_crops_geometry_idx on public.audit_crops using gist (geometry);

