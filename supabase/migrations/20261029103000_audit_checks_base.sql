-- Automated audit checks: one framework for every check (DT-1481, parent DT-1470).
--
-- Every check (dataset evaluation, georeferencing, acquisition date, prediction
-- quality, phenology later) plugs in the same way:
--
--   audit.checks -> audit.check_versions -> audit.runs -> evidence -> audit.assessments
--
-- Evidence is what a run looked at: check-specific run evidence (jsonb), the
-- crops it judged and the stored images people and models saw. Assessments hold
-- one row per person and per model, per crop or per dataset, per layer. They are
-- append-only: a correction is a new row, so agreement between assessors stays
-- measurable. Dataset verdicts are derived from these rows by versioned rules
-- that each check owns; they reach the audit form as dataset_audit_suggestions.
-- Model assessments are visible to auditors, the audit worker and the analyst
-- role only. See docs/audit-checks.md.
set local lock_timeout = '5s';

-- The framework has its own schema, served by the API (api.schemas in
-- supabase/config.toml; production: docs/audit-checks.md). Nothing in it is granted
-- by default: anon gets nothing, authenticated only the grants and policies below.
create schema audit;
revoke all on schema audit from public;
grant usage on schema audit to authenticated, service_role, analyst;
alter default privileges for role postgres in schema audit revoke all on tables from public, anon, authenticated;
alter default privileges for role postgres in schema audit revoke all on sequences from public, anon, authenticated;
alter default privileges for role postgres in schema audit revoke all on functions from public, anon;

create type audit.check_mode as enum ('review_all', 'review_uncertain', 'auto_apply');
create type audit.run_status as enum ('queued', 'running', 'done', 'failed');
-- rule: a deterministic check (band statistics, duplicate hash), stored like a model.
create type audit.assessor_kind as enum ('person', 'model', 'rule');
-- One vocabulary for every check:
--   ok      passes: keep, georef good, date valid, layer fine
--   minor   passes with a problem: keep but fix or reprocess, layer error below 20%
--   major   fails: exclude, georef poor, date mismatch, 20%+ of the layer wrong
--   unsure  could not decide: uncertain call, crop not assessable; goes to a person
create type audit.verdict as enum ('ok', 'minor', 'major', 'unsure');

-- The audit worker writes as the processor account; one place to change that.
create function internal.is_audit_worker()
returns boolean
language sql stable set search_path = ''
as $$
	select coalesce((select auth.jwt() ->> 'email') = 'processor@deadtrees.earth', false);
$$;

create function internal.can_read_audit_checks()
returns boolean
language sql stable set search_path = ''
as $$
	select internal.is_audit_worker() or public.can_audit() or public.can_operate();
$$;

revoke all on function internal.is_audit_worker() from public, anon;
revoke all on function internal.can_read_audit_checks() from public, anon;
grant execute on function internal.is_audit_worker() to authenticated, service_role;
grant execute on function internal.can_read_audit_checks() to authenticated, service_role;

-- Rows that must never change once written (assessments, benchmark pins).
create function internal.reject_audit_row_update()
returns trigger
language plpgsql set search_path = ''
as $$
begin
	raise exception '% rows are append-only; insert a new row instead', tg_table_name using errcode = '55000';
end;
$$;

